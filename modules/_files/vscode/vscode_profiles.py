"""Register the Nix-declared VS Code profiles and write their Nix-owned extension entries.

Run by modules/vscode.nix as a home-manager activation step, after the default profile's
extensions.json was regenerated:

    vscode_profiles.py --spec SPEC.json

SPEC.json is generated by Nix: {"profiles": {NAME: {"nix": bool, "entries": PATH}},
"flags": {...}, "local": [{"id", "version", "dir"}], "shared": [ID, ...]}. `local` are
extensions that are hand-built directories rather than registry packages (the Turbo Vision
theme): every profile needs them because settings.json, shared through `useDefaultFlags`,
names the theme. `shared` are extensions that live in the DEFAULT profile, installed there
at runtime because they are unfree and so cannot be built through Nix: their entry is
copied from the default profile's extensions.json into every profile. A profile does not
inherit the default profile's extensions (measured), which is why Dev Containers, installed
by hand in the default profile, showed up as "Recommended: Install" in every other window.
`entries` is a store path holding the profile's Nix extensions in
extensions.json format (pkgs.vscode-utils.toExtensionJson, locations in /nix/store).
`nix: true` marks a stack profile whose content Nix owns; `nix: false` is a profile such
as `oneoff` that Nix only creates and seeds, and that +vscode-ext fills at runtime.

WHY NOT programs.vscode.profiles. Measured in the pinned home-manager
(mkVscodeModule.nix): the first non-default profile makes `mutableExtensionsDir` an
assertion failure, turns ~/.vscode/extensions into one read-only buildEnv symlink, makes
every profile's extensions.json a store symlink and registers the profile in storage.json
without `useDefaultFlags`. That ends every runtime install. This script keeps all of it
writable: it merges instead of owning.

THE RULES IT FOLLOWS
  * A profile's extensions.json is merged, never replaced: entries pointing into
    /nix/store are Nix's and are rewritten, every other entry is somebody's runtime
    install and survives.
  * storage.json is rewritten only when a profile is missing or its flags differ, and
    never while VS Code runs: VS Code rewrites that file when it exits, which would
    silently drop the registration. In that case the script says so and exits 1; the
    caller tolerates exactly that code and the next `just switch` retries.
  * Everything else in storage.json stays as it is.
  * Profiles inherit settings and keybindings from the default profile (`useDefaultFlags`)
    but NOT its extensions (measured: a new profile lists none), hence each profile's
    entries are the general set plus the stack set.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

HOME = Path(os.environ.get("HOME", "~")).expanduser()
USER_DIR = HOME / "Library/Application Support/Code/User"
STORAGE = USER_DIR / "globalStorage/storage.json"
PROFILES_DIR = USER_DIR / "profiles"
ROOT = HOME / ".vscode/extensions-profiles"
SIDECAR = ROOT / ".nix-profiles.json"
SHARED_SIDECAR = ROOT / ".shared-extensions.json"   # read by +vscode-ext install --global
DEFAULT_REGISTRY = HOME / ".vscode/extensions/extensions.json"


def log(msg: str) -> None:
    print(f"vscode-profiles: {msg}", file=sys.stderr)


def read_json(path: Path, default):
    try:
        return json.loads(path.read_text())
    except FileNotFoundError:
        return default


def write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f"{path.name}.tmp.{os.getpid()}")
    tmp.write_text(text)
    os.replace(tmp, path)


def is_nix(entry: dict) -> bool:
    loc = entry.get("location") or {}
    return str(loc.get("fsPath") or loc.get("path") or "").startswith("/nix/store/")


DEFAULT_EXT_ROOT = HOME / ".vscode/extensions"


def heal(entries: list[dict]) -> list[dict]:
    """Drop a `relativeLocation` that does not match the entry's real location.

    VS Code resolves a non-empty `relativeLocation` against ~/.vscode/extensions and
    IGNORES `location`. toExtensionJson writes one (`relativeLocation = <id>`) for every
    store path, and the 19 general extensions survive that only because home-manager also
    symlinks them into ~/.vscode/extensions. Every other entry showed up in the
    Extensions view as "Unable to read file ~/.vscode/extensions/<id>/package.json"
    (measured 2026-11-05) while `code --list-extensions` listed it happily.
    """
    for e in entries:
        loc = e.get("location") or {}
        path = str(loc.get("fsPath") or loc.get("path") or "")
        if e.get("relativeLocation") and path and \
                not path.startswith(str(DEFAULT_EXT_ROOT) + "/"):
            e.pop("relativeLocation")
    return entries


def vscode_running() -> bool:
    return subprocess.run(["pgrep", "-x", "Code"], capture_output=True).returncode == 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    spec = json.loads(Path(ap.parse_args().spec).read_text())
    flags = spec["flags"]
    profiles = spec["profiles"]

    storage = read_json(STORAGE, {})
    listed = storage.setdefault("userDataProfiles", [])
    registered = {p["name"]: p for p in listed}
    missing = [n for n in profiles if n not in registered]
    drifted = [n for n in profiles
               if n in registered and registered[n].get("useDefaultFlags") != flags]
    refused: list[str] = []
    if missing or drifted:
        if vscode_running():
            refused = missing                 # a missing profile cannot be written to at all
            if drifted:
                log(f"flags differ for {', '.join(drifted)}; they are corrected the next "
                    f"time this runs with VS Code closed")
            drifted = []
            missing = []
        for n in missing:
            entry = {"name": n, "location": n}
            listed.append(entry)
            registered[n] = entry
        for n in missing + drifted:
            registered[n]["useDefaultFlags"] = dict(flags)
        if missing or drifted:
            write_atomic(STORAGE, json.dumps(storage, indent=4))
            log(f"registered/updated: {', '.join(missing + drifted)}")

    shared_ids = [i.lower() for i in spec.get("shared", [])]
    default_entries = {e["identifier"]["id"].lower(): e
                       for e in read_json(DEFAULT_REGISTRY, [])}
    shared = []
    for i in shared_ids:
        if i in default_entries:
            shared.append(default_entries[i])
        else:
            log(f"shared extension {i} is not installed in the default profile; "
                f"`+vscode-ext install --global {i}` installs it (cooled)")

    ok = skip = 0
    for name, p in profiles.items():
        if name in refused:
            log(f"{name}: not registered, VS Code is running")
            continue
        loc = registered[name].get("location", name)
        target = PROFILES_DIR / loc / "extensions.json"
        wanted = heal(json.loads(Path(p["entries"]).read_text()))
        raw = read_json(target, [])               # compare against what is on disk, not
        current = heal(json.loads(json.dumps(raw)))   # the healed copy, or a broken file looks current
        (target.parent / "globalStorage").mkdir(parents=True, exist_ok=True)
        shared_have = {e["identifier"]["id"].lower() for e in shared}
        keep = [e for e in current if not is_nix(e)
                and e["identifier"]["id"].lower() not in shared_have]
        keep += [json.loads(json.dumps(e)) for e in shared]    # the default's entry, newest copy
        keep_ids = {e["identifier"]["id"].lower() for e in keep}
        merged = [e for e in wanted if e["identifier"]["id"].lower() not in keep_ids] + keep
        for loc in spec.get("local", []):
            if loc["id"].lower() not in {e["identifier"]["id"].lower() for e in merged}:
                merged.append({"identifier": {"id": loc["id"]}, "version": loc["version"],
                               "location": {"$mid": 1, "fsPath": loc["dir"],
                                            "path": loc["dir"], "scheme": "file"},
                               })
        if raw == merged and target.exists():
            skip += 1
            continue
        write_atomic(target, json.dumps(merged))
        ok += 1

    ROOT.mkdir(parents=True, exist_ok=True)
    sidecar = json.dumps({"profiles": sorted(n for n, p in profiles.items() if p["nix"])})
    if not SIDECAR.exists() or SIDECAR.read_text() != sidecar:
        write_atomic(SIDECAR, sidecar)

    shared_json = json.dumps({"ids": spec.get("shared", [])})
    if not SHARED_SIDECAR.exists() or SHARED_SIDECAR.read_text() != shared_json:
        write_atomic(SHARED_SIDECAR, shared_json)

    log(f"{ok} written, {skip} already current, {len(refused)} refused"
        + (f" ({', '.join(refused)}: quit VS Code and run `+vscode-profiles`)"
           if refused else ""))
    return 1 if refused else 0


if __name__ == "__main__":
    sys.exit(main())
